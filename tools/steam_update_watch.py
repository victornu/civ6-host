MANIFEST_NAME = f"appmanifest_{APP_ID}.acf"
COMMON_DIR = "steamapps/common/Sid Meier's Civilization VI"

XP2_CORE = "DLC/Expansion2/Binaries/Win64/GameCore_XP2_FinalRelease.dll"
