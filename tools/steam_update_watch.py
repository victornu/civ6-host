@dataclass
class FileEdit:
    """One mechanical replacement, applied as a raw byte swap."""

    relative: str
    old: str
    new: str
    count: int = 0
    path: Path | None = field(default=None, compare=False)


def _walk_sources(repo_root: Path) -> Iterable[Path]:
    for path in sorted(Path(repo_root).rglob("*")):
        if not path.is_file():
            continue
        if _SKIP_PARTS & set(path.parts):
            continue
        if path.suffix not in _EDITABLE_SUFFIXES:
            continue
        yield path


def profile_id_for(sha256: str) -> str:
    return f"xp2-gamecore-current-{sha256[:8]}"


def plan_edits(
    repo_root: Path,
    *,
    old_sha256: str,
    new_sha256: str,
    old_size: int | None,
    new_size: int,
    old_profile_id: str,
    new_profile_id: str,
) -> list[FileEdit]:
    """Plan the mechanical re-anchor edits for a new installed XP2 image.

    * the profile id follows the new short hash wherever it is named;
    * the SHA-256 literal follows the new image unless the module records what a
      *capture* saw (``EVIDENCE_RECORDED_IMAGE_FILES``), which must stay
      fail-closed until the capture is repeated;
    * the byte size follows too, only where it is pinned next to that hash.
    """
    root = Path(repo_root)
    edits: list[FileEdit] = []
    for path in _walk_sources(root):
        relative = path.relative_to(root).as_posix()
        try:
            text = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        pairs: list[tuple[str, str]] = []
        if old_profile_id and old_profile_id in text:
            pairs.append((old_profile_id, new_profile_id))
        if old_sha256 and old_sha256 in text and relative not in EVIDENCE_RECORDED_IMAGE_FILES:
            pairs.append((old_sha256, new_sha256))
        if old_size and relative not in EVIDENCE_RECORDED_IMAGE_FILES:
            if str(old_size) in text and old_sha256 and old_sha256 in text:
                pairs.append((str(old_size), str(new_size)))
        for old, new in pairs:
            if old == new:
                continue
            edits.append(FileEdit(relative, old, new, text.count(old), path))
    return edits


def apply_edits(repo_root: Path, edits: Sequence[FileEdit]) -> list[tuple[str, int]]:
    """Apply byte-level replacements, preserving each file's line endings."""
    root = Path(repo_root)
    applied: list[tuple[str, int]] = []
    for edit in edits:
        path = Path(edit.path) if edit.path is not None else root / edit.relative
        data = path.read_bytes()
        old = edit.old.encode("utf-8")
        new = edit.new.encode("utf-8")
        count = data.count(old)
        if not count:
            continue
        path.write_bytes(data.replace(old, new))
        applied.append((edit.relative, count))
    return applied


def _run(command: Sequence[str], cwd: Path, env: Mapping[str, str] | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(list(command), cwd=str(cwd), capture_output=True, text=True, env=dict(env) if env else None)


def _git(repo_root: Path, *args: str) -> subprocess.CompletedProcess:
    return _run(("git", *args), repo_root)


def test_environment(repo_root: Path) -> dict[str, str]:
    env = dict(os.environ)
    source = str(Path(repo_root) / "src")
    existing = env.get("PYTHONPATH")
    env["PYTHONPATH"] = source if not existing else source + os.pathsep + existing
    return env


def run_offline_tests(
    repo_root: Path,
    tests: Sequence[str],
    *,
    python: str | None = None,
) -> tuple[int, str]:
    command = [python or sys.executable, "-m", "pytest", *tests, "-q"]
    completed = _run(command, Path(repo_root), test_environment(repo_root))
    return completed.returncode, (completed.stdout or "") + (completed.stderr or "")


def commit_message(
    *,
    old_sha256: str,
    new_sha256: str,
    old_size: int | None,
    new_size: int,
    old_profile_id: str,
    new_profile_id: str,
) -> str:
    return (
        f"re-anchor the current XP2 execution image to {new_sha256[:8]} (Steam update)\n"
        "\n"
        "The Steam update replaced the installed XP2 GameCore DLL:\n"
        "\n"
        f"  sha256 {new_sha256}\n"
        f"  {new_size} bytes (was {old_sha256}, {old_size if old_size is not None else '?'} bytes)\n"
        "\n"
        f"execution_images now pins those bytes and registers the profile as\n"
        f"'{new_profile_id}'. References that select or name the previous profile\n"
        "follow it, and the installed-image SHA-256/size constants that describe the\n"
        "DLL follow the new bytes. The captured ABI reference image is unchanged.\n"
        "\n"
        "The pinned source spans in execution_images.py were derived against the\n"
        "previous installed image and are deliberately left alone. verify() can only\n"
        "prove the proof files exist and hash as pinned, not that their spans still\n"
        "correspond to the new image, so the gates that compare a stored proof with\n"
        "the live image now fail closed. Those source proofs must be re-derived with\n"
        "REA/Ghidra before any native admission is claimed on the new image.\n"
        "\n"
        f"Planned by tools/steam_update_watch.py; old profile id {old_profile_id or '-'}.\n"
        "Offline only: no GameCore load, no game launch.\n"
        "\n"
        f"{COMMIT_TRAILER}"
    )


@dataclass(frozen=True)
class ApplyResult:
    branch: str
    applied: tuple[tuple[str, int], ...]
    tests_rc: int
    test_output: str
    committed: bool
    detail: str


def apply_reanchor(
    repo_root: Path,
    *,
    old_sha256: str,
    new_sha256: str,
    old_size: int | None,
    new_size: int,
    old_profile_id: str,
    new_profile_id: str,
    tests: Sequence[str] = DEFAULT_TESTS,
    run_tests: Callable[[Path, Sequence[str]], tuple[int, str]] | None = None,
    allow_dirty: bool = False,
) -> ApplyResult:
    """Create ``feat/reanchor-xp2-<short>``, apply the edits, test and commit."""
    root = Path(repo_root)
    branch = f"feat/reanchor-xp2-{new_sha256[:8]}"
    status = _git(root, "status", "--porcelain")
    if status.returncode != 0:
        raise SystemExit("not a git repository (or git is unavailable)")
    if status.stdout.strip() and not allow_dirty:
        raise SystemExit("working tree is dirty; commit or stash before --apply")
    existing = _git(root, "rev-parse", "--verify", "--quiet", branch)
    if existing.returncode == 0:
        create = _git(root, "checkout", branch)
    else:
        create = _git(root, "checkout", "-b", branch)
    if create.returncode != 0:
        raise SystemExit(f"cannot check out {branch}: {create.stderr.strip()}")
    edits = plan_edits(
        root,
        old_sha256=old_sha256,
        new_sha256=new_sha256,
        old_size=old_size,
        new_size=new_size,
        old_profile_id=old_profile_id,
        new_profile_id=new_profile_id,
    )
    applied = tuple(apply_edits(root, edits))
    if not applied:
        return ApplyResult(branch, (), 0, "", False, "nothing to apply")
    runner = run_tests or (lambda repo, files: run_offline_tests(repo, files))
    rc, output = runner(root, tests)
    if rc != 0:
        return ApplyResult(
            branch, applied, rc, output, False,
            "offline tests failed; edits left in the working tree, nothing committed",
        )
    stage = _git(root, "add", "-u")
    if stage.returncode != 0:
        return ApplyResult(branch, applied, rc, output, False, f"git add failed: {stage.stderr.strip()}")
    message = commit_message(
        old_sha256=old_sha256,
        new_sha256=new_sha256,
        old_size=old_size,
        new_size=new_size,
        old_profile_id=old_profile_id,
        new_profile_id=new_profile_id,
    )
    commit = _git(root, "commit", "-m", message)
    if commit.returncode != 0:
        return ApplyResult(branch, applied, rc, output, False, f"git commit failed: {commit.stderr.strip()}")
    return ApplyResult(branch, applied, rc, output, True, f"committed on {branch}")


