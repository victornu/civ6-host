def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Wait for a Civ VI Steam update, then compare and re-anchor the GameCore pins.",
    )
    parser.add_argument("--steam-root", default=DEFAULT_STEAM_ROOT, help="Steam installation directory")
    parser.add_argument("--interval", type=float, default=30.0, help="seconds between manifest reads")
    parser.add_argument("--max-wait-min", type=float, default=120.0, help="give up after this many minutes")
    parser.add_argument("--repo-root", default=str(Path(__file__).resolve().parent.parent))
    parser.add_argument("--apply", action="store_true", help="create the re-anchor branch, apply, test and commit")
    parser.add_argument("--yes", action="store_true", help="skip the interactive confirmation for --apply")
    parser.add_argument("--tests", nargs="*", default=list(DEFAULT_TESTS), help="offline tests to run with --apply")
    parser.add_argument("--once", action="store_true", help="skip waiting and compare the current manifest state")
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    steam_root = Path(args.steam_root)
    manifest = manifest_path(steam_root)
    read = lambda: read_manifest(manifest)  # noqa: E731
    if args.once:
        try:
            state = manifest_state(read())
        except OSError as error:
            wait = WaitResult(False, str(error), None, 0, 0.0)
        else:
            wait = WaitResult(state.settled, "read once", state, 1, 0.0)
    else:
        print(f"waiting for Steam to finish updating app {APP_ID} (buildid stability 2 reads)...")
        wait = wait_for_update(read, interval_seconds=args.interval, max_wait_minutes=args.max_wait_min)
    actual = identify_installed(steam_root)
    pins = pinned_files()
    rows = compare(pins, actual)
    admitted = admission(actual)
    changed = [row for row in rows if row.changed]
    xp2 = next((row for row in rows if row.name == "xp2_core"), None)
    other = [row for row in changed if row.name != "xp2_core"]
    edits: list[FileEdit] = []
    if xp2 is not None and xp2.changed and xp2.new_sha256 and xp2.new_size:
        edits = plan_edits(
            Path(args.repo_root),
            old_sha256=xp2.old_sha256,
            new_sha256=xp2.new_sha256,
            old_size=xp2.old_size,
            new_size=xp2.new_size,
            old_profile_id=pins["xp2_core"].profile_id,
            new_profile_id=profile_id_for(xp2.new_sha256),
        )
    print(format_report(wait, rows, admitted, edits, steam_root=steam_root))
    if not changed:
        return 0
    if other:
        print(
            "\nNote: "
            + ", ".join(f"{row.name} ({row.profile_id or 'no profile'})" for row in other)
            + " also moved. Those are separate execution-image profiles with their own captured\n"
            "evidence, so this tool only reports them; re-anchor each one deliberately."
        )
    if xp2 is None or not xp2.changed:
        return 1
    if not wait.ok:
        print("\nSteam has not reported a finished update; re-run once it settles. Nothing applied.")
        return 2
    if not args.apply:
        print("\nDry run only. Re-run with --apply to create the branch and commit the re-anchor.")
        return 1
    if not args.yes:
        answer = input("Apply these edits on a new branch and commit? [y/N] ")
        if answer.strip().lower() not in {"y", "yes"}:
            print("aborted")
            return 1
    result = apply_reanchor(
        Path(args.repo_root),
        old_sha256=xp2.old_sha256,
        new_sha256=xp2.new_sha256,
        old_size=xp2.old_size,
        new_size=xp2.new_size,
        old_profile_id=pins["xp2_core"].profile_id,
        new_profile_id=profile_id_for(xp2.new_sha256),
        tests=args.tests,
    )
    for relative, count in result.applied:
        print(f"  edited {relative} ({count} replacement(s))")
    if result.test_output:
        print(result.test_output.rstrip())
    print(result.detail)
    return 0 if result.committed else 3


