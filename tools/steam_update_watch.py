"""Watch the Civ VI Steam update and keep the execution-image pins in sync.

The host pins the installed GameCore images by SHA-256. A Steam update replaces
those binaries, so the pins stop matching and every static check fails closed.
This utility makes that moment boring:

  1. poll ``steamapps/appmanifest_289070.acf`` until Steam reports the update as
     finished (``BytesToDownload == 0``, ``UpdateResult == 0``) and the
     ``buildid`` has been stable for two consecutive reads;
  2. hash the four pinned binaries in place and compare them with the pins in
     ``civ6_host.runtime.execution_images``;
  3. print the pin mapping and, when a hash moved, the exact edits that would
     re-anchor the repository. ``--apply`` performs them on a new branch, runs
     the offline tests and commits with the required trailer.

It never launches the game, never loads a GameCore, never writes outside the
repository (and never writes under ``C:\\civ6-private``). It reads the manifest
and the installed binaries only.
"""
from __future__ import annotations

