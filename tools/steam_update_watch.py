def hash_file(path: str | os.PathLike[str]) -> tuple[str, int]:
    """Return ``(sha256, size)`` for a file, refusing anything oversized."""
    digest = hashlib.sha256()
    size = 0
    with open(path, "rb") as handle:
        while True:
            chunk = handle.read(1024 * 1024)
            if not chunk:
                break
            size += len(chunk)
            digest.update(chunk)
    return digest.hexdigest(), size


@dataclass(frozen=True)
class ActualFile:
    name: str
    path: Path
    sha256: str
    size_bytes: int
    error: str = ""


def identify_installed(steam_root: Path) -> dict[str, ActualFile]:
    """Hash every watched binary under ``steam_root``; never writes anything."""
    common = Path(steam_root) / COMMON_DIR
    found: dict[str, ActualFile] = {}
    for name, relative in WATCHED_FILES:
        path = common / relative
        try:
            sha256, size = hash_file(path)
            found[name] = ActualFile(name, path, sha256, size)
        except OSError as error:
            found[name] = ActualFile(name, path, "", 0, f"{type(error).__name__}: {error}")
    return found


@dataclass(frozen=True)
class PinnedFile:
    name: str
    profile_id: str
    sha256: str
    size_bytes: int | None
    note: str = ""


def pinned_files(execution_images=None) -> dict[str, PinnedFile]:
    """Read the installed-image pins out of ``execution_images``."""
    module = execution_images if execution_images is not None else _import_execution_images()
    pins = {
        "xp2_core": PinnedFile(
            "xp2_core",
            module._PROFILE.id,
            module._CURRENT_CORE_SHA256,
            module._CURRENT_CORE_SIZE_BYTES,
        ),
        "xp1_core": PinnedFile(
            "xp1_core",
            module._XP1_PROFILE.id,
            module._XP1_PROFILE.image_sha256,
            module._XP1_PROFILE.image_size_bytes,
        ),
        "base_core": PinnedFile(
            "base_core",
            module._BASE_PROFILE.id,
            module._BASE_PROFILE.image_sha256,
            module._BASE_PROFILE.image_size_bytes,
        ),
        "game_exe": PinnedFile(
            "game_exe",
            "",
            "",
            None,
            "the exe is pinned by the capture modules, not by execution_images",
        ),
    }
    try:  # informational only: the captured ABI reference for the base image
        from civ6_host.runtime.saved_load_profiles import BASE_CORE_SHA256

        pins["base_core"] = PinnedFile(
            "base_core",
            pins["base_core"].profile_id,
            pins["base_core"].sha256,
            pins["base_core"].size_bytes,
            f"captured ABI reference {BASE_CORE_SHA256}",
        )
    except Exception:  # pragma: no cover - optional context only
        pass
    return pins


def _import_execution_images():
    try:
        from civ6_host.runtime import execution_images
    except ImportError as error:  # pragma: no cover - depends on PYTHONPATH
        raise SystemExit(
            "cannot import civ6_host.runtime.execution_images; run with "
            f"PYTHONPATH=src ({error})"
        ) from error
    return execution_images


@dataclass(frozen=True)
class ComparisonRow:
    name: str
    profile_id: str
    old_sha256: str
    old_size: int | None
    new_sha256: str
    new_size: int
    changed: bool
    detail: str = ""


def compare(pins: Mapping[str, PinnedFile], actual: Mapping[str, ActualFile]) -> list[ComparisonRow]:
    rows: list[ComparisonRow] = []
    for name, _ in WATCHED_FILES:
        pin = pins.get(name)
        got = actual.get(name)
        if got is None:
            continue
        pinned_sha = pin.sha256 if pin else ""
        pinned_size = pin.size_bytes if pin else None
        if got.error:
            detail = got.error
        elif not pinned_sha:
            detail = pin.note if pin else "no pin"
        elif pinned_sha != got.sha256 or (pinned_size is not None and pinned_size != got.size_bytes):
            detail = "installed bytes differ from the pin"
        else:
            detail = "matches the pin"
        changed = bool(got.error) or bool(
            pinned_sha and (pinned_sha != got.sha256 or (pinned_size is not None and pinned_size != got.size_bytes))
        )
        status = "CHANGED" if changed else ("ERROR" if got.error else "ok")
        rows.append(
            ComparisonRow(
                name=name,
                profile_id=pin.profile_id if pin else "",
                old_sha256=pinned_sha,
                old_size=pinned_size,
                new_sha256=got.sha256,
                new_size=got.size_bytes,
                changed=changed,
                detail=f"{status}: {detail}",
            )
        )
    return rows


@dataclass(frozen=True)
class Admission:
    profile_id: str
    admitted: bool
    detail: str


def admission(actual: Mapping[str, ActualFile], execution_images=None) -> Admission:
    """Ask ``execution_images.select`` whether the installed XP2 image is the pin."""
    module = execution_images if execution_images is not None else _import_execution_images()
    profile_id = module._PROFILE.id
    got = actual.get("xp2_core")
    if got is None or got.error:
        return Admission(profile_id, False, "the installed XP2 image could not be hashed")
    try:
        profile = module.select(profile_id, core_path=str(got.path))
    except ValueError as error:
        return Admission(profile_id, False, str(error))
    if profile.image_sha256 != got.sha256 or profile.image_size_bytes != got.size_bytes:
        return Admission(
            profile_id,
            False,
            "installed image is not the pinned image "
            f"({got.sha256}, {got.size_bytes} bytes)",
        )
    return Admission(profile_id, True, "the current profile pins the installed image")


