_KV_RE = re.compile(r'"([^"]*)"\s+"([^"]*)"')


def parse_appmanifest(text: str) -> dict[str, str]:
    """Return the flat key/value pairs of a Steam ``appmanifest_*.acf`` file."""
    values: dict[str, str] = {}
    for key, value in _KV_RE.findall(text):
        values.setdefault(key, value)
    return values


def manifest_path(steam_root: Path) -> Path:
    return Path(steam_root) / "steamapps" / MANIFEST_NAME


def read_manifest(path: Path) -> dict[str, str]:
    return parse_appmanifest(Path(path).read_text(encoding="utf-8", errors="replace"))


@dataclass(frozen=True)
class ManifestState:
    buildid: str
    bytes_to_download: int
    update_result: int

    @property
    def settled(self) -> bool:
        return self.bytes_to_download == 0 and self.update_result == 0


def manifest_state(values: Mapping[str, str]) -> ManifestState:
    """Read the three fields that decide whether Steam is still working."""

    def number(key: str) -> int:
        # A key that is not there yet means Steam has not told us the state, so
        # the update cannot be called finished.
        raw = str(values.get(key, "")).strip()
        if not raw:
            return -1
        try:
            return int(raw)
        except ValueError:
            return -1

    return ManifestState(
        buildid=str(values.get("buildid", "")).strip(),
        bytes_to_download=number("BytesToDownload"),
        update_result=number("UpdateResult"),
    )


@dataclass(frozen=True)
class WaitResult:
    ok: bool
    reason: str
    state: ManifestState | None
    polls: int
    elapsed_seconds: float


def wait_for_update(
    read: Callable[[], Mapping[str, str]],
    *,
    interval_seconds: float = 30.0,
    max_wait_minutes: float = 120.0,
    required_stable_reads: int = 2,
    clock: Callable[[], float] = time.monotonic,
    sleeper: Callable[[float], None] = time.sleep,
) -> WaitResult:
    """Poll until the manifest is settled and its buildid is stable.

    ``required_stable_reads`` consecutive settled reads that agree on the
    buildid end the wait. ``read`` is injected so the poll logic is testable
    without Steam.
    """
    if required_stable_reads < 1:
        raise ValueError("required_stable_reads must be at least 1")
    deadline = clock() + max_wait_minutes * 60.0
    started = clock()
    polls = 0
    last: ManifestState | None = None
    stable = 0
    reason = "timed out waiting for Steam to finish the update"
    while True:
        polls += 1
        try:
            state = manifest_state(read())
        except FileNotFoundError:
            state = None
            reason = "appmanifest_289070.acf is not readable"
        except OSError:
            state = None
            reason = "appmanifest_289070.acf is not readable"
        else:
            if state.settled and last is not None and state.buildid == last.buildid:
                stable += 1
            elif state.settled:
                stable = 1
            else:
                stable = 0
                reason = (
                    "Steam is still working: "
                    f"BytesToDownload={state.bytes_to_download} "
                    f"UpdateResult={state.update_result}"
                )
            last = state
            if state.settled and stable >= required_stable_reads:
                return WaitResult(True, "update finished", state, polls, clock() - started)
        if clock() >= deadline:
            return WaitResult(False, reason, last, polls, clock() - started)
        sleeper(interval_seconds)


