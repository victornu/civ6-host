def short(sha256: str) -> str:
    return sha256[:12] if sha256 else "-"


def format_report(
    wait: WaitResult | None,
    rows: Sequence[ComparisonRow],
    admission_result: Admission | None,
    edits: Sequence["FileEdit"] = (),
    *,
    steam_root: Path | None = None,
) -> str:
    lines: list[str] = ["Civ VI Steam update watch", ""]
    if steam_root is not None:
        lines.append(f"steam root : {steam_root}")
    if wait is not None:
        state = wait.state
        buildid = state.buildid if state else "-"
        lines.append(
            f"manifest   : {'settled' if wait.ok else 'NOT settled'} after {wait.polls} poll(s), "
            f"{wait.elapsed_seconds:.0f}s, buildid {buildid or '-'} ({wait.reason})"
        )
    lines.append("")
    header = f"{'file':<10} {'pin (sha256 / bytes)':<36} {'installed (sha256 / bytes)':<36} status"
    lines.append(header)
    lines.append("-" * len(header))
    for row in rows:
        old = f"{short(row.old_sha256)} / {row.old_size if row.old_size is not None else '-'}"
        new = f"{short(row.new_sha256)} / {row.new_size if not row.new_sha256 else row.new_size}"
        lines.append(f"{row.name:<10} {old:<36} {new:<36} {row.detail}")
    lines.append("")
    if admission_result is not None:
        lines.append(
            f"admission  : profile {admission_result.profile_id} "
            f"{'admits' if admission_result.admitted else 'does NOT admit'} the installed XP2 image "
            f"({admission_result.detail})"
        )
    changed = [row for row in rows if row.changed]
    lines.append("")
    if not changed:
        lines.append("No pin changes needed.")
        return "\n".join(lines)
    lines.append(f"{len(changed)} file(s) moved; the pins must be re-anchored:")
    for row in changed:
        lines.append(
            f"  {row.name}: {short(row.old_sha256)} -> {short(row.new_sha256)} "
            f"({row.old_size if row.old_size is not None else '-'} -> {row.new_size} bytes)"
        )
    if edits:
        lines.append("")
        lines.append("Exact edits to apply:")
        for edit in edits:
            lines.append(
                f"  {edit.relative} (pattern {edit.old!r} -> {edit.new!r}, {edit.count} occurrence(s))"
            )
    else:
        lines.append("")
        lines.append(
            "No XP2 re-anchor is planned: the current profile, its profile id and the sha "
            "literals already match, so there is nothing for --apply to do on this row."
        )
    return "\n".join(lines)


